import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createClient } from '@supabase/supabase-js';

const root = fileURLToPath(new URL('../', import.meta.url));
const adminEmail = 'admin@tribe-saarthi.example.invalid';

export function localSettings(status) {
  const url = new URL(status.API_URL);
  assert.ok(url.protocol === 'http:' && ['localhost', '127.0.0.1'].includes(url.hostname)
    && !url.username && !url.password && url.pathname === '/' && !url.search && !url.hash,
  'Setup requires a local Supabase URL. Hosted settings are never overwritten.');
  const publishableKey = status.PUBLISHABLE_KEY || status.ANON_KEY;
  const serviceRoleKey = status.SERVICE_ROLE_KEY || status.SECRET_KEY;
  let publicRole;
  try { publicRole = JSON.parse(Buffer.from(publishableKey.split('.')[1], 'base64url')).role; } catch { /* New publishable keys are opaque. */ }
  assert.ok(typeof publishableKey === 'string' && !/\s/.test(publishableKey)
    && (publishableKey.startsWith('sb_publishable_') || publicRole === 'anon'), 'Local public API key is missing or unsafe.');
  assert.ok(typeof serviceRoleKey === 'string' && serviceRoleKey.length > 0, 'Local service key is missing.');
  return { url: url.origin, publishableKey, serviceRoleKey };
}

export function frontendEnv(settings) {
  return `# Generated by npm run backend:setup; local development only.\nVITE_APP_MODE=pilot\nVITE_SUPABASE_URL=${settings.url}\nVITE_SUPABASE_PUBLISHABLE_KEY=${settings.publishableKey}\nVITE_PILOT_ADAPTER_MODE=simulated\n`;
}

export async function provisionAdmin(admin, auth, credentials) {
  assert.equal(credentials.email, adminEmail, 'Unexpected local administrator email.');
  assert.ok(typeof credentials.password === 'string' && credentials.password.length >= 12, 'Invalid local administrator credentials.');
  let login = await auth.signInWithPassword(credentials);
  if (login.error?.code === 'invalid_credentials') {
    const created = await admin.auth.admin.createUser({ ...credentials, email_confirm: true });
    assert.ok(!created.error, 'Local administrator creation failed; existing passwords are never reset.');
    login = await auth.signInWithPassword(credentials);
  }
  assert.ok(!login.error && login.data?.user, 'Local administrator login failed.');
  const id = login.data.user.id;
  const existing = await admin.from('pilot_accounts').select('role,active').eq('id', id).maybeSingle();
  assert.ok(!existing.error, 'Local account lookup failed; check migrations.');
  if (existing.data) {
    assert.ok(existing.data.role === 'admin' && existing.data.active, 'Existing administrator access requires manual review.');
  } else {
    const saved = await admin.from('pilot_accounts').insert({ id, email: credentials.email, name: 'Local administrator', role: 'admin', active: true });
    assert.ok(!saved.error, 'Local administrator scope could not be saved. Rerun setup to retry.');
  }
}

function cli(args) {
  // Capture output because `start` and `status` include server credentials.
  const result = spawnSync(process.platform === 'win32' ? 'supabase.exe' : 'supabase', args, { cwd: root, encoding: 'utf8' });
  assert.ok(!result.error && result.status === 0,
    `Supabase ${args.slice(0, 2).join(' ')} failed. Check that the Supabase CLI and Docker Desktop are installed and running.`);
  return result.stdout;
}

async function setup() {
  console.log('Starting local Supabase and applying pending migrations…');
  cli(['start']);
  cli(['migration', 'up', '--local']);
  const settings = localSettings(JSON.parse(cli(['status', '--output', 'json'])));
  cli(['db', 'query', '--local', '--file', 'supabase/seed.sql']);
  const directory = resolve(root, '.backend');
  await mkdir(directory, { recursive: true });
  const credentialsPath = resolve(directory, 'admin.json');
  let credentials;
  try { credentials = JSON.parse(await readFile(credentialsPath, 'utf8')); }
  catch (error) {
    if (error.code !== 'ENOENT') throw error;
    credentials = { email: adminEmail, password: `Local!${randomUUID()}` };
    await writeFile(credentialsPath, JSON.stringify(credentials, null, 2) + '\n', { mode: 0o600, flag: 'wx' });
  }
  const options = { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } };
  const admin = createClient(settings.url, settings.serviceRoleKey, options);
  const client = createClient(settings.url, settings.publishableKey, options);
  await provisionAdmin(admin, client.auth, credentials);
  await writeFile(resolve(root, '.env.backend.local'), frontendEnv(settings), { mode: 0o600 });
  await writeFile(resolve(directory, 'functions.env'), 'PILOT_ALLOWED_ORIGINS=http://localhost:5173,http://127.0.0.1:5173\nPILOT_INVITE_REDIRECT_URL=http://localhost:5173\nPILOT_ADAPTER_MODE=simulated\n', { mode: 0o600 });
  console.log('Local database, private buckets, configuration and administrator are ready.\nRun npm run backend:serve, then npm run dev:local in another terminal.\nLocal login: .backend/admin.json. Local email inbox: http://localhost:54324.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  setup().catch(error => { console.error(error instanceof assert.AssertionError ? error.message : 'Backend setup failed. Check local Supabase services and configuration.'); process.exitCode = 1; });
}
